def convertir_y_formatear(lineas, nombre="data"):
    # Separar cada fila en partes
    filas = [linea.strip().split() for linea in lineas]

    # Normalizar mes y día: siempre 2 dígitos
    for fila in filas:
        fila[1] = fila[1].zfill(2)  # mes
        fila[2] = fila[2].zfill(2)  # día

    # Ordenar por fecha (año, mes, día)
    filas.sort(key=lambda f: (int(f[0]), int(f[1]), int(f[2])))

    # Calcular ancho máximo por columna
    max_lens = [max(len(fila[i]) for fila in filas) for i in range(len(filas[0]))]

    # Construir bloque alineado
    bloque = f"{nombre} = [\n"
    for fila in filas:
        partes = [fila[i].ljust(max_lens[i]) for i in range(len(fila))]
        bloque += "    [" + ", ".join(f"'{p}'" for p in partes) + "],\n"
    bloque += "]\n"

    return bloque

